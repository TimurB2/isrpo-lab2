def area(a, h): 
    '''
    Возвращает площадь треугольника с задаными стороной и длинной высоты опущенной на нее
        Параметры:
        a(float): сторона
        h(float): высота опущенная на сторону
        Возвращаемое значение(float): площадь треугольника со стороной a и высотой h
    '''
    return a * h / 2 

def perimeter(a, b, c): 
    '''
    Возвращает периметр треугольника с задаными сторонами
        Параметры:
        a(float): сторона
        b(float): сторона
        c(float): сторона
        Возвращаемое значение(float): периметр треугольника со сторонами a,b и c
    '''
    return a + b + c 
