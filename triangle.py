def area(a, h): 
    '''
    Возвращает площадь треугольника с задаными стороной и длинной высоты опущенной на нее
        Парамаметры:
        a(int or float): сторона
        h(int or float): высота опущенная на сторону
        Возвращаемое значение(int or float): площадь треугольника со стороной a и высотой h
    '''
    return a * h / 2 

def perimeter(a, b, c): 
    '''
    Возвращает периметр треугольника с задаными сторонами
        Парамаметры:
        a(int or float): сторона
        b(int or float): сторона
        c(int or float): сторона
        Возвращаемое значение(int or float): периметр треугольника со сторонами a,b и c
    '''
    return a + b + c 
