import math


def area(r):
    '''
    Возвращает площадь окружности с заданым радиусом r
        Параметр: r(float): радиус окружности
        Возвращаемое значение(float): площадь окружности радиуса r
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Возвращает длину окружности с заданым радиусом r
        Параметр: r(float): радиус окружности
        Возвращаемое значение(float): длина окружности радиуса r
    '''
    return 2 * math.pi * r

